        /// <summary>
        /// 无主键表的兜底条件:逐列按值匹配(值为 NULL 时用 IS NULL),避免只用第一个字段导致误改/误删多行
        /// </summary>
        /// <param name="row">数据行</param>
        /// <param name="useOldValue">true 时取编辑前的旧值(修改行/删除行使用)</param>
        private string BuildNoPrimaryKeyWhere(DataRow row, bool useOldValue)
        {
            var conds = new List<string>();
            foreach (DataColumn col in row.Table.Columns)
            {
                var value = useOldValue ? dg.GetOldValue(row, col.ColumnName) : row[col];
                var columnName = Db.GetEscapeName(_model.Lj, col.ColumnName);
                conds.Add(value == null || value == DBNull.Value
                    ? $"{columnName} IS NULL"
                    : $"{columnName}={Db.GetValueByType(value, col.DataType)}");
            }
            return string.Join(" AND ", conds);
        }

        /// <summary>
        /// 根据界面编辑生成SQL
        /// </summary>
        /// <param name="noPkWhere">是否用了无主键兜底(按所有字段匹配):保存前由调用方弹确认框</param>
        /// <returns></returns>
        private string Shengcheng(out bool noPkWhere)
        {
            noPkWhere = false;
            var changes = dg.GetChanges();

            // 1. 获取新增行
            var added = changes.AddedRows;

            // 2. 获取删除行
            var deleted = changes.DeletedRows;

            // 3. 获取修改行（列+旧值+新值）
            var modified = changes.ModifiedCellsInfo;

            string msg = string.Empty;

            // --------------------
            // 新增行
            // --------------------
            if (added.Count > 0)
            {
                foreach (DataRow row in added)
                {
                    var tableName = GetTableName(row.Table);
                    var sql = $"INSERT INTO {Db.GetEscapeName(_model.Lj, tableName)}(";
                    var values = "VALUES(";
                    foreach (DataColumn col in row.Table.Columns)
                    {
                        bool isPrimaryKey = DataTableEditDataGrid.IsPrimaryKey(row.Table, col);//是否主键
                        string columnName = Db.GetEscapeName(_model.Lj, col.ColumnName); // 列名
                        string valueStr = Db.GetValueByType(row[col], col.DataType);
                        sql += $"{columnName},";
                        values += $"{valueStr},";
                    }
                    sql = sql.TrimEnd(',') + ")";
                    values = values.TrimEnd(',') + ");";
                    msg = msg + sql + values;
                }
            }

            // --------------------
            // 删除行
            // --------------------
            if (deleted.Count > 0)
            {
                foreach (DataRow row in deleted)
                {
                    var tableName = GetTableName(row.Table);
                    var sql = $"DELETE FROM {Db.GetEscapeName(_model.Lj, tableName)}";
                    var where = " WHERE ";
                    foreach (DataColumn col in row.Table.Columns)
                    {
                        bool isPrimaryKey = DataTableEditDataGrid.IsPrimaryKey(row.Table, col);//是否主键
                        string columnName = Db.GetEscapeName(_model.Lj, col.ColumnName); // 列名
                        string oldValue = Db.GetValueByType(dg.GetOldValue(row, col.ColumnName), col.DataType);
                        if (isPrimaryKey)
                        {
                            where += $"{columnName}={oldValue} AND ";
                        }
                    }
                    //没有主键:用所有字段的内容匹配(值为NULL的用IS NULL),避免只用第一个字段匹配到多行导致误删
                    if (where == " WHERE ")
                    {
                        where += BuildNoPrimaryKeyWhere(row, true) + " AND ";
                        noPkWhere = true;
                    }
                    where = where.Substring(0, where.Length - 5) + ";";
                    msg = msg + sql + where;
                }
            }

            // --------------------
            // 修改行
            // --------------------
            if (modified.Count > 0)
            {
                foreach (var item in modified)
                {
                    DataRow row = item.Key;
                    var tableName = GetTableName(row.Table);
                    var sql = $"UPDATE {Db.GetEscapeName(_model.Lj, tableName)} SET ";
                    var where = " WHERE ";
                    foreach (DataColumn col in row.Table.Columns)
                    {
                        bool isPrimaryKey = DataTableEditDataGrid.IsPrimaryKey(row.Table, col);//是否主键
                        string columnName = Db.GetEscapeName(_model.Lj, col.ColumnName); // 列名
                        string valueStr = Db.GetValueByType(row[col], col.DataType);
                        string oldValue = Db.GetValueByType(dg.GetOldValue(row, col.ColumnName), col.DataType);
                        if (item.Value.Any(p => p == col.ColumnName))
                        {
                            sql += $"{columnName}={valueStr},";
                        }
                        if (isPrimaryKey)
                        {
                            where += $"{columnName}={oldValue} AND ";
                        }
                    }
                    sql = sql.TrimEnd(',');
                    //没有主键:用所有字段的内容匹配(值为NULL的用IS NULL),避免只用第一个字段匹配到多行导致误改
                    if (where == " WHERE ")
                    {
                        where += BuildNoPrimaryKeyWhere(row, true) + " AND ";
                        noPkWhere = true;
                    }
                    where = where.Substring(0, where.Length - 5) + ";";
                    msg = msg + sql + where;

                }
            }
            return msg;
        }

        private void MenuBaocun_Click(object sender, RoutedEventArgs e)
        {
            //查询画面的结果只读(改数据走"查看数据"页),这里兜一道底,避免快捷键等入口绕过
            if (_model?.ReadOnly == true)
            {
                return;
            }
            //保存中不重复提交(防 Ctrl+S 连按)
            if (_saving)
            {
                return;
            }
            //把编辑框里还没失焦的输入提交到数据行,避免 Ctrl+S 保存漏掉当前编辑的单元格
            _ = dg.CommitEdit(DataGridEditingUnit.Cell, true);
            _ = dg.CommitEdit(DataGridEditingUnit.Row, true);
            //MongoDB 结果:按文档改动生成 updateOne/deleteOne/insertOne
            if (_model.MongoEditor != null)
            {
                var mongoChanges = dg.GetChanges();
                _saving = true;
                SetLoading(true);
                _ = Task.Factory.StartNew(
                   new Action(() =>
                   {
                       var err = _model.MongoEditor.Save(mongoChanges);
                       Dispatcher.Invoke(new Action(() =>
                       {
                           _saving = false;
                           SetLoading(false);
                           if (string.IsNullOrEmpty(err))
                           {
                               dg.RemoveDeletedRowsFromView();
                               dg.ClearEditState();
                           }
                           else
                           {
                               Msg.Warning(err);
                           }
                       }));
                   }));
                return;
            }
            var sql = Shengcheng(out var noPkWhere);
            if (string.IsNullOrEmpty(sql))
            {
                Oops.Warning("没有任何变更");
                return;
            }
            //无主键表按所有字段匹配条件可能命中多行:保存前确认,取消则不执行
            if (noPkWhere && !Msg.Question("该表没有主键,更新/删除将按所有字段内容匹配定位数据,可能影响多行,是否继续保存?"))
            {
                return;
            }
            try
            {
                _saving = true;
                SetLoading(true);
                _ = Task.Factory.StartNew(
                   new Action(() =>
                   {
                       _ = Db.GetDataTable(_model.Lj, sql, out var _, out var isErr);
                       Dispatcher.Invoke(new Action(() =>
                       {
                           _saving = false;
                           if (!isErr)
                           {
                               dg.RemoveDeletedRowsFromView();
                               dg.ClearEditState();
                           }
                           SetLoading(false);
                       }));
                   }));
            }
            catch (Exception ex)
            {
                _saving = false;
                Msg.Warning(ex.Message);
            }
        }

