        /// <summary>
        /// 按列名设置列的显示/隐藏(列还没生成时会先记住,列生成后自动生效)
        /// </summary>
        public void SetColumnVisible(string columnName, bool visible)
        {
            if (string.IsNullOrEmpty(columnName))
            {
                return;
            }
            if (visible)
            {
                _hiddenColumns.Remove(columnName);
            }
            else
            {
                _hiddenColumns.Add(columnName);
            }
            ApplyColumnVisibility();
        }

        private void ApplyColumnVisibility()
        {
            if (dg == null)
            {
                return;
            }
            foreach (var col in dg.Columns)
            {
                var name = col.Header?.ToString();
                var visibility = !string.IsNullOrEmpty(name) && _hiddenColumns.Contains(name)
                    ? Visibility.Collapsed
                    : Visibility.Visible;
                //只有真正变化时才写:Visibility 每次赋值都会触发列/单元格重建,全量赋值在列多时非常卡
                if (col.Visibility != visibility)
                {
                    col.Visibility = visibility;
                }
            }
        }

