        /// <summary>
        /// 创建sql点击
        /// </summary>
        /// <param name="sender"></param>
        /// <param name="e"></param>
        private void Cj_Click(object sender, RoutedEventArgs e)
        {
            if (dg.SelectedCells.Count == 0)
            {
                Msg.Warning("请选择要创建SQL的行或单元格");
                return;
            }
            var mi = (MenuItem)sender;
            var name = mi.Name;
            var cell = dg.SelectedCells[dg.SelectedCells.Count - 1];
            var rowView = (DataRowView)cell.Item;
            var row = rowView.Row;
            //MongoDB 结果:生成对应的 MongoDB 命令
            if (_model.MongoEditor != null)
            {
                var kind = name == "SELECTWHERE" ? "SELECTWHERE"
                    : name.StartsWith("SELECT") ? "SELECT"
                    : name.StartsWith("INSERT") ? "INSERT"
                    : name.StartsWith("UPDATE") ? "UPDATE"
                    : name.StartsWith("DELETE") ? "DELETE"
                    : null;
                if (kind == null)
                {
                    return;
                }
                //"已选列"相关项(名字以 X 结尾,或"已选列为条件")只用选中的列
                var scope = name.EndsWith("X") || kind == "SELECTWHERE" ? UIHelp.GetColumns(dg) : null;
                var cmd = _model.MongoEditor.BuildRowCommand(kind, row, scope);
                if (!string.IsNullOrEmpty(cmd))
                {
                    var w = new SqlWindow(cmd)
                    {
                        Owner = System.Windows.Window.GetWindow(this)
                    };
                    _ = w.ShowDialog();
                }
                return;
            }
            var dt = row.Table;
            var tableName = GetTableName(dt);
            var where = " WHERE ";
            var columns = UIHelp.GetColumns(dg);
            string sql = string.Empty;
            if (name == "SELECTWHERE")
            {
                //"以已选列为条件":输出全部列,WHERE 只取选中的列(用当前行的值)
                var conds = new List<string>();
                foreach (DataColumn col in dt.Columns)
                {
                    if (!columns.Any(p => p == col.ColumnName))
                    {
                        continue;
                    }
                    var colName = Db.GetEscapeName(_model.Lj, col.ColumnName);
                    conds.Add($"{colName}={Db.GetValueByType(row[col], col.DataType)}");
                }
                var allColumns = string.Join(",", dt.Columns.Cast<DataColumn>()
                    .Select(p => Db.GetEscapeName(_model.Lj, p.ColumnName)));
                sql = $"SELECT {allColumns} FROM {Db.GetEscapeName(_model.Lj, tableName)}";
                if (conds.Count > 0)
                {
                    sql += " WHERE " + string.Join(" AND ", conds);
                }
                sql += ";";
            }
            else if (name.StartsWith("SELECT"))
            {
                sql = "SELECT ";
                foreach (DataColumn col in dt.Columns)
                {
                    bool isPrimaryKey = DataTableEditDataGrid.IsPrimaryKey(dt, col);//是否主键
                    string columnName = Db.GetEscapeName(_model.Lj, col.ColumnName); // 列名
                    string valueStr = Db.GetValueByType(row[col], col.DataType);
                    if (!name.EndsWith("X") || columns.Any(p => p == col.ColumnName))
                    {
                        sql += $"{columnName},";
                    }
                    if (isPrimaryKey)
                    {
                        where += $"{columnName}={valueStr} AND ";
                    }
                }
                sql = sql.TrimEnd(',') + " FROM " + Db.GetEscapeName(_model.Lj, tableName);
                //没有主键:用所有字段的内容匹配(值为NULL的用IS NULL)
                if (where == " WHERE ")
                {
                    where += BuildNoPrimaryKeyWhere(row, false) + " AND ";
                }
                where = where.Substring(0, where.Length - 5) + ";";
                sql += where;
            }
            else if (name.StartsWith("INSERT"))
            {
                sql = $"INSERT INTO {Db.GetEscapeName(_model.Lj, tableName)}(";
                var values = "VALUES(";
                foreach (DataColumn col in dt.Columns)
                {
                    bool isPrimaryKey = DataTableEditDataGrid.IsPrimaryKey(dt, col);//是否主键
                    string columnName = Db.GetEscapeName(_model.Lj, col.ColumnName); // 列名
                    string valueStr = Db.GetValueByType(row[col], col.DataType);
                    if (!name.EndsWith("X") || columns.Any(p => p == col.ColumnName))
                    {
                        sql += $"{columnName},";
                        values += $"{valueStr},";
                    }
                }
                sql = sql.TrimEnd(',') + ")";
                values = values.TrimEnd(',') + ");";
                sql += values;
            }
            else if (name.StartsWith("UPDATE"))
            {
                sql = $"UPDATE {Db.GetEscapeName(_model.Lj, tableName)} SET ";
                foreach (DataColumn col in dt.Columns)
                {
                    bool isPrimaryKey = DataTableEditDataGrid.IsPrimaryKey(dt, col);//是否主键
                    string columnName = Db.GetEscapeName(_model.Lj, col.ColumnName); // 列名
                    string valueStr = Db.GetValueByType(row[col], col.DataType);
                    if (!name.EndsWith("X") || columns.Any(p => p == col.ColumnName))
                    {
                        sql += $"{columnName}={valueStr},";
                    }
                    if (isPrimaryKey)
                    {
                        where += $"{columnName}={valueStr} AND ";
                    }
                }
                sql = sql.TrimEnd(',');
                //没有主键:用所有字段的内容匹配(值为NULL的用IS NULL),避免只用第一个字段匹配到多行导致误改
                if (where == " WHERE ")
                {
                    where += BuildNoPrimaryKeyWhere(row, false) + " AND ";
                }
                where = where.Substring(0, where.Length - 5) + ";";
                sql += where;
            }
            else if (name.StartsWith("DELETE"))
            {
                sql = $"DELETE FROM {Db.GetEscapeName(_model.Lj, tableName)}";
                foreach (DataColumn col in dt.Columns)
                {
                    bool isPrimaryKey = DataTableEditDataGrid.IsPrimaryKey(dt, col);//是否主键
                    string columnName = Db.GetEscapeName(_model.Lj, col.ColumnName); // 列名
                    string valueStr = Db.GetValueByType(row[col], col.DataType);
                    if (isPrimaryKey)
                    {
                        where += $"{columnName}={valueStr} AND ";
                    }
                }
                //没有主键:用所有字段的内容匹配(值为NULL的用IS NULL),避免只用第一个字段匹配到多行导致误删
                if (where == " WHERE ")
                {
                    where += BuildNoPrimaryKeyWhere(row, false) + " AND ";
                }
                where = where.Substring(0, where.Length - 5) + ";";
                sql += where;
            }
            var sqlWindow = new SqlWindow(sql.SqlFormat());
            System.Windows.Window mainWindow = System.Windows.Window.GetWindow(this);
            sqlWindow.Owner = mainWindow;
            _ = sqlWindow.ShowDialog();
        }

