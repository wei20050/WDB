        /// <summary>
        /// 右键"查看":只看单元格完整内容(查询结果只读时用,打开的窗口不带保存按钮)
        /// </summary>
        private void MenuChakan_Click(object sender, RoutedEventArgs e)
        {
            var cell = dg.SelectedCells.LastOrDefault();
            if (cell.Column == null)
            {
                return;
            }
            //列名:表头 HeaderText.ToString() 即字段名
            var name = cell.Column.Header?.ToString();
            var text = string.Empty;
            if (!string.IsNullOrEmpty(name) && cell.Item is DataRowView drv)
            {
                var col = drv.Row.Table.Columns[name];
                if (col != null)
                {
                    //NULL 与表格里的显示口径一致,免得"看到有值、点开是空"
                    text = drv.Row[col] == DBNull.Value ? DataTableEditDataGrid.Null : drv.Row[col].ToString();
                }
            }
            var wb = new WenBen(text, true);
            wb.Owner = System.Windows.Window.GetWindow(this);
            _ = wb.ShowDialog();
        }

        private void MenuBianji_Click(object sender, RoutedEventArgs e)
        {
            if (!dg.SelectedCells.Any()) return;

            var lastCell = dg.SelectedCells.Last();

            dg.SelectedCells.Clear();
            dg.SelectedCells.Add(lastCell);
            dg.CurrentCell = lastCell;
            dg.BeginEdit();

            var content = lastCell.Column.GetCellContent(lastCell.Item);
            var editingTextBox = content as TextBox;
            if (editingTextBox != null)
            {
                var wb = new WenBen(editingTextBox.Text);
                System.Windows.Window mainWindow = System.Windows.Window.GetWindow(this);
                wb.Owner = mainWindow;
                if (wb.ShowDialog() == true)
                {
                    dg.SelectedCells.Clear();
                    dg.SelectedCells.Add(lastCell);
                    dg.BeginEdit();
                    editingTextBox.Text = wb._nr;
                    dg.CommitEdit();
                }
            }

            dg.CommitEdit();
            dg.CancelEdit();

        }

