        /// <summary>
        /// 从DataTable名称中取出真实表名(名称形如"tbl (1)")
        /// </summary>
        private static string GetTableName(DataTable dt)
        {
            var tableName = dt?.TableName ?? string.Empty;
            var index = tableName.IndexOf(' ');
            return index > 0 ? tableName.Substring(0, index) : tableName;
        }

        /// <summary>
        /// 向上查找视觉树中的父级元素
        /// </summary>
        public static T FindAncestor<T>(DependencyObject obj) where T : DependencyObject
        {
            while (obj != null)
            {
                if (obj is T ancestor)
                {
                    return ancestor;
                }
                obj = VisualTreeHelper.GetParent(obj);
            }
            return null;
        }

        /// <summary>
        /// 向上查找实现了指定接口的父级元素
        /// </summary>
        public static T FindAncestorInterface<T>(DependencyObject obj) where T : class
        {
            while (obj != null)
            {
                if (obj is T ancestor)
                {
                    return ancestor;
                }
                obj = VisualTreeHelper.GetParent(obj);
            }
            return null;
        }

