        /// <summary>
        /// 右键点击的时候刷新筛选内容
        /// </summary>
        /// <param name="sender"></param>
        /// <param name="e"></param>
        private void dg_MouseRightButtonDown(object sender, MouseButtonEventArgs e)
        {
            if (_model == null)
            {
                return;
            }
            var cellText = string.Empty;
            var cellColor = string.Empty;
            _mousePos = e.GetPosition(dg);
            // 获取鼠标下的单元格
            DataGridCell cell = UIHelp.GetCellUnderMouse(dg, _mousePos);
            string header;
            if (cell == null)
            {
                DataGridColumnHeader column = UIHelp.GetColumnHeaderUnderMouse(dg, _mousePos);
                if (column == null)
                {
                    return;
                }
                header = column.Content.ToString();
            }
            else
            {
                if (!cell.IsSelected)
                {
                    dg.SelectedCells.Clear();
                    cell.IsSelected = true;
                }
                header = cell.Column?.Header?.ToString();
                //单元格处于编辑态时内容可能是TextBox,这里做兼容处理,避免空引用
                var tb = cell.Content as TextBlock;
                cellText = tb?.Text ?? cell.Content?.ToString() ?? string.Empty;
                cellColor = tb?.Foreground.ToString() ?? string.Empty;
            }
            //MongoDB 结果:列名不做 SQL 转义(否则会去建 SQL 连接)
            string cellHeader = _model.MongoEditor != null ? header : Db.GetEscapeName(_model.Lj, header);

            miOrderBy.Items.Clear();
            SetOrderByMenuItem(cellHeader, true);
            SetOrderByMenuItem(cellHeader, false);

            miFilter.Items.Clear();
            SetMenuItem("NULL 条件");
            SetMenuItem(cellHeader, "IS NULL");
            SetMenuItem(cellHeader, "IS NOT NULL");
            SetMenuItem();
            //单元格不为空且为正常查出来的值才渲染
            if (!string.IsNullOrEmpty(cellText) && cellColor != "#FFA9A9A9")
            {
                var index = cellText.IndexOf('\r');
                if (index > 0)
                {
                    cellText = cellText.Substring(0, index);
                }
                SetMenuItem("单元格的值");
                SetMenuItems(cellHeader, cellText);
                SetMenuItem();
            }
            var txt = SafeClipboard.GetText();
            if (txt.Length > 100)
            {
                txt = txt.Substring(0, 100);
            }
            if (!string.IsNullOrWhiteSpace(txt))
            {
                var index = txt.IndexOf('\r');
                if (index > 0)
                {
                    txt = txt.Substring(0, index);
                }
                SetMenuItem("剪切板的值");
                SetMenuItems(cellHeader, txt);
                SetMenuItem();
            }
            SetMenuItem("自定义");
            SetMenuItems(cellHeader, null);
        }

        /// <summary>
        /// 给筛选菜单添加子菜单
        /// </summary>
        private void SetMenuItem(string cellHeader = null, string cellText = null, string key = null)
        {
            if (cellHeader == null)
            {
                miFilter.Items.Add(new Separator { Margin = new Thickness { Right = 10 } });
            }
            else
            {
                var tag = $"{cellHeader ?? string.Empty}{key ?? string.Empty}{cellText ?? string.Empty}";
                var header = tag.Split('\r')[0];
                header = header.Length > 50 ? header.Substring(0, 50) + " ..." : header;
                var m = new MenuItem
                {
                    Header = header,
                    Tag = tag
                };
                if (cellText == null)
                {
                    m.IsEnabled = false;
                }
                else
                {
                    m.Click += Mi_Click;
                }
                miFilter.Items.Add(m);
            }
        }

        /// <summary>
        /// 给筛选菜单添加一组子菜单
        /// </summary>
        private void SetMenuItems(string cellHeader, string cellText)
        {
            var strArr = new string[] { "=", "<>", ">", "<", "LIKE" };
            foreach (var str in strArr)
            {
                if (str == "LIKE")
                {
                    SetMenuItem(cellHeader, $"'%{cellText}%'", str);
                }
                else
                {
                    SetMenuItem(cellHeader, $"'{cellText}'", str);
                }
            }
        }

        /// <summary>
        /// 筛选菜单点击事件
        /// </summary>
        /// <param name="sender"></param>
        /// <param name="e"></param>
        private void Mi_Click(object sender, RoutedEventArgs e)
        {
            var mi = (MenuItem)sender;
            var header = mi.Tag.ToString();
            if (header.EndsWith("''") || header.EndsWith("'%%'"))
            {
                var wb = new WenBen(string.Empty);
                wb.Title = "录入筛选值";
                System.Windows.Window mainWindow = System.Windows.Window.GetWindow(this);
                wb.Owner = mainWindow;
                if (wb.ShowDialog() == true)
                {
                    if (header.EndsWith("''"))
                    {
                        header = header.Replace("''", $"'{wb._nr}'");
                    }
                    if (header.EndsWith("'%%'"))
                    {
                        header = header.Replace("'%%'", $"'%{wb._nr}%'");
                    }
                }
                else
                {
                    return;
                }
            }
            //新的查看数据页:条件加进[筛选&排序]面板并直接执行
            if (_host != null)
            {
                _host.ApplyFilter(header);
                return;
            }
            if (_tabView == null)
            {
                return;
            }
            var txt = _tabView.TextEditor.Text.Trim();
            var start = Db.GetFirstTableNameEndIndex(txt.Substring(0, _tabView.TextEditor.SelectionStart));
            var str = txt.Substring(start, _tabView.TextEditor.SelectionStart - start);
            if (str.EndsWith(";"))
            {
                _tabView.TextEditor.SelectionStart--;
            }
            var limitIndex = str.IndexOf("limit", StringComparison.OrdinalIgnoreCase);
            if (limitIndex >= 0)
            {
                _tabView.TextEditor.SelectionStart = start + limitIndex - 1;
            }
            string where;
            if (str.IndexOf("where", StringComparison.OrdinalIgnoreCase) >= 0)
            {
                if (str.TrimEnd().EndsWith("where", StringComparison.CurrentCultureIgnoreCase))
                {
                    where = " " + header;
                }
                else
                {
                    where = " AND " + header;
                }
            }
            else
            {
                where = " WHERE " + header;
            }

            _tabView.TextEditor.Document.Insert(_tabView.TextEditor.SelectionStart, where);

            Oops.Ok("筛选条件已插入SQL编辑器!");
        }

